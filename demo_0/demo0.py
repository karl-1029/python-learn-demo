"""
============================================================
【自考08074 运算符全通关指南】
============================================================
本代码涵盖了Python所有核心运算符及易错考点：

【第一部分：算术运算符（+ - * / // % **）】
1. 基础四则：+ - * /
2. 除法三兄弟：
   /  ：真除法，结果永远是浮点数。
   // ：整除，向下取整（重点记负数情况）。
   %  ：取模，结果符号跟【除数】一致。
3. 幂运算（**）：优先级极高，且有“右结合性”。

【第二部分：运算符的“多重身份”（易错）】
+ 号：数字是加法，字符串/列表是“拼接”。
* 号：数字是乘法，字符串/列表是“重复”多次。
注意：字符串和列表不支持 - 和 /。

【第三部分：逻辑短路与比较】
and：遇假即停；or：遇真即停。结果不一定是True/False。
== 比较值，is 比较内存地址。
============================================================
"""

print("abs(-10) =", abs(10))   # 结果：10

# ==========================================
# 1. 基础算术运算符（数字）
# ==========================================
print("--- 1. 基础加减乘除 ---")
a = 10
b = 3

print("加法 (a + b):", a + b)
print("减法 (a - b):", a - b)
print("乘法 (a * b):", a * b)
print("真除法 (a / b):", a / b)   # 结果是 3.333... (永远是 float)

# 整除与取余（正数情况）
print("整除 (10 // 3):", 10 // 3) # 结果是 3
print("取余 (10 % 3):", 10 % 3)   # 结果是 1
print("幂运算 (2 ** 3):", 2 ** 3) # 结果是 8

# 负号的特殊用法
print("负号 (-a):", -a)           # 结果是 -10


# ==========================================
# 2. 负数除法避坑（自考最爱考）
# ==========================================
print("\n--- 2. 负数除法避坑 ---")
# 牢记：// 是向下取整（往数轴左边走），% 的符号看除数
print("-10 / 3 =", -10 / 3)     # -3.333...
print("-10 // 3 =", -10 // 3)   # 不是 -3，是 -4！（因为 -3.33 向下取整是 -4）
print("-10 % 3 =", -10 % 3)     # 不是 -1，是 2！ （因为 -10 = 3 * (-4) + 2）

print("10 // -3 =", 10 // -3)   # 结果是 -4
print("10 % -3 =", 10 % -3)     # 结果也是 -2（符号跟除数 -3 一致）


# ==========================================
# 3. 运算符的“多重身份”（字符串与列表）
# ==========================================
print("\n--- 3. 字符串与列表的运算 ---")
s1 = "Hello"
s2 = "World"
lst1 = [1, 2]
lst2 = [3, 4]

# 加号：拼接
print("字符串相加 (s1 + s2):", s1 + s2)       # HelloWorld
print("列表相加 (lst1 + lst2):", lst1 + lst2) # [1, 2, 3, 4]

# 乘号：重复
print("字符串乘3 (s1 * 3):", s1 * 3)          # HelloHelloHello
print("列表乘2 (lst1 * 2):", lst1 * 2)        # [1, 2, 1, 2]

# 【易错警告】字符串和列表不能相减，也不能相除，会直接报错！
# print(s1 - s2)  # TypeError: unsupported operand type(s) for -: 'str' and 'str'


# ==========================================
# 4. 幂运算（**）的优先级与结合性
# ==========================================
print("\n--- 4. 幂运算 ---")
# 优先级：高于乘除，高于负号
print("2 + 3 ** 2 =", 2 + 3 ** 2)   # 先算 3**2=9，再算 2+9=11
print("-2 ** 2 =", -2 ** 2)         # 相当于 -(2**2)，结果是 -4
print("(-2) ** 2 =", (-2) ** 2)     # 加了括号，结果是 4

# 结合性：右结合（从右往左算）
print("2 ** 3 ** 2 =", 2 ** 3 ** 2) # 相当于 2 ** (3**2) = 2**9 = 512


# ==========================================
# 5. 赋值运算符
# ==========================================
print("\n--- 5. 赋值与解包 ---")
x = 5
x += 3   # 相当于 x = x + 3
print("x += 3 后，x =", x)  # 8

x *= 2   # 相当于 x = x * 2
print("x *= 2 后，x =", x)  # 16

# 多重赋值 / 解包
m, n = 10, 20
print("初始 m, n =", m, n)
m, n = n, m # 直接交换，不需要中间变量
print("交换后 m, n =", m, n)


# ==========================================
# 6. 逻辑运算符的“短路”现象
# ==========================================
print("\n--- 6. 逻辑短路 ---")
# and 遇假即停，or 遇真即停。返回的是具体的值！
print("3 and 5 =", 3 and 5)   # 3是真，返回后面的 5
print("0 and 5 =", 0 and 5)   # 0是假，直接返回 0
print("3 or 5 =", 3 or 5)     # 3是真，直接返回 3
print("0 or 5 =", 0 or 5)     # 0是假，返回后面的 5


# ==========================================
# 7. 比较运算符与身份运算符
# ==========================================
print("\n--- 7. == 与 is 的区别 ---")
a = [1, 2, 3]
b = [1, 2, 3]
print("a == b 结果:", a == b)  # 比较“值”，True
print("a is b 结果:", a is b)  # 比较“内存地址”，False（因为生成了两个列表对象）


# ==========================================
# 8. 优先级综合计算（教材第60页原题）
# ==========================================
print("\n--- 8. 优先级综合 ---")
# 原式：16 / 4 - 2 ** 5 * 8 / 4 % 5 / 2
result = 16 / 4 - 2 ** 5 * 8 / 4 % 5 / 2
print("计算结果:", result) # 结果：2.0