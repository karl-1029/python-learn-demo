# 1. 创建复数的两种常见方式
print("--- 1. 创建复数 ---")
# 方式一：直接写，注意虚部后面必须带 j 或 J
z1 = 3 + 4j
# 方式二：使用 complex() 内置函数 (实部, 虚部)
z2 = complex(2, -5)

print("z1 =", z1)
print("z2 =", z2)
print("z1的类型:", type(z1))

# 2. 提取实部(real)和虚部(imag)
print("\n--- 2. 提取实部和虚部 ---")
# 注意：提取出来的都是浮点数(float)
print("z1的实部:", z1.real)
print("z1的虚部:", z1.imag)

# 3. 复数的基本运算
print("\n--- 3. 复数运算 ---")
# 加法：实部加实部，虚部加虚部
print("z1 + z2 =", z1 + z2)
# 乘法：按多项式展开 (3+4j)*(2-5j) = 6 - 15j + 8j - 20j² = 26 - 7j (因为 j² = -1)
print("z1 * z2 =", z1 * z2)

# 4. 共轭复数 (conjugate)
print("\n--- 4. 共轭复数 ---")
# 共轭复数：实部不变，虚部变号。3+4j 的共轭是 3-4j
print("z1的共轭复数:", z1.conjugate())

# 5. 求复数的模 (abs函数)
print("\n--- 5. 求复数的模 ---")
# 模 = 根号下(实部² + 虚部²) = 根号下(3² + 4²) = 5.0
print("z1的模(绝对值):", abs(z1))

# 6. 易错点：只用 1j 表示纯虚数，不能只写 j
print("\n--- 6. 纯虚数的写法 ---")
# x = 3 + j   # 错误！会报 NameError: name 'j' is not defined
y = 3 + 1j    # 正确：必须写 1j
print("y =", y)








